-- 004：户型上的「地面材质替换」（AC-10 重定性为「矢量图上换地面材质」）
--
-- ══════════════════════════════════════════════════════════════════
-- 为什么是**独立一列**，而不是塞进 `parsed_data`
-- ══════════════════════════════════════════════════════════════════
-- `parsed_data` 里放的是**解析产物**：它是可重放的（AC-32 的黄金路径
-- 就冻结了一份它的存档）。用户在这里换的地板颜色**不是解析出来的**，
-- 是人的选择。混进去之后：
--
--   · "重放解析结果"要回答"这是解析出的还是人选过的" —— 答不了
--   · 换一次地板就动一次 parsed_data，而那是重建 3D 与诊断的输入
--
-- 所以它是 `house_layouts` 上的一列，与解析产物并列而不是嵌套。
--
-- ══════════════════════════════════════════════════════════════════
-- 形状
-- ══════════════════════════════════════════════════════════════════
-- `{"0": "DS-FL-201", "3": "QY-TL-101"}`
--   key   = 房间下标（`scene.rooms` 的枚举顺序，与 SVG 里
--           `<polygon id="room-N">`、热区里的 `room_index` 同一个）
--   value = 材料目录里的 product id
--
-- ⚠️ JSON 的键只能是字符串，读回来要 `int()` 转换 —— 这一层由
--    `repository.load_floor_materials` 负责，调用方拿到的永远是 int 键。
--
-- ⚠️ 为什么不建成独立的表（`layout_floor_materials`）：
--    这份数据**只有一个读法**——"这台户型的每间房用了什么地面材料"，
--    没有按材料反查户型、没有历史版本、没有多用户并发改同一份的需求。
--    建表要配主键、外键、级联删除，而收益是零。等真有第二种读法再拆。

ALTER TABLE house_layouts
    ADD COLUMN IF NOT EXISTS floor_materials JSONB;

COMMENT ON COLUMN house_layouts.floor_materials IS
    '房间下标 → 地面材料 product id 的映射（AC-10 局部替换）。'
    '与 parsed_data 并列：那是解析产物，这是用户的选择。';
