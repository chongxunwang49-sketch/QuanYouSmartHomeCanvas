-- 003 design_plans 补 space_plan
-- ══════════════════════════════════════════════════════════════════
--
-- 起因：做「3D 带装修」时想让摆放**跟着方案走**（用方案里逐房间写的
-- 家具短语去匹配目录条目），于是要按 plan_id 取那套方案 ——
-- 然后发现 `space_plan` **根本没落库**。
--
-- 那是个真疏漏：`space_plan` 是 A-03 的核心产物（逐房间的功能安排与
-- 家具清单），001 里落了预算、风险、材料、环境，唯独漏了它。
-- 更值得记的是**它当时没被发现的原因**：`_plan_row` 是照着"表里有
-- 哪些列"写的，而不是照着"方案里有哪些产物"写的 —— 顺着表的形状
-- 走，就看不见"表本身少了一格"。
--
-- 教训写在这里：**列清单应当对着产物清单核一遍**，而不是对着已有的表。
ALTER TABLE design_plans ADD COLUMN IF NOT EXISTS space_plan JSONB;
